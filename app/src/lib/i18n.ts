// Client-safe UI strings. Keep this module free of server-only imports.

export type Lang = "ja" | "en" | "zh" | "ko";
export const SUPPORTED_LANGS = ["en", "ja", "zh", "ko"] as const satisfies readonly Lang[];

export const LANG_LABELS: Record<Lang, string> = {
  en: "English",
  ja: "日本語",
  zh: "中文",
  ko: "한국어",
};

/** Used as the target prompt hint and for locale-aware date formatting. */
export const LANG_NAMES: Record<Lang, string> = {
  en: "English",
  ja: "Japanese",
  zh: "Simplified Chinese",
  ko: "Korean",
};

export const LANG_LOCALES: Record<Lang, string> = {
  en: "en-US",
  ja: "ja-JP",
  zh: "zh-CN",
  ko: "ko-KR",
};

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (SUPPORTED_LANGS as readonly string[]).includes(value);
}

/** English is the base locale; other translations fall back to it. */
export type UiEntry = { en: string } & Partial<Record<Exclude<Lang, "en">, string>>;

/** `{name}` placeholders are filled from `vars`. */
export function pickEntry(entry: UiEntry | undefined, lang: Lang, vars?: Record<string, string | number>): string {
  let s = entry?.[lang] ?? entry?.en ?? "";
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

